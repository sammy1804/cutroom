/**
 * Builds the Skill Registry from skills/**\/SKILL.md (+ skill.ts).
 *   pnpm skills:build
 * Writes skills/registry.generated.ts (metadata, instructions, module imports)
 * and a schema.json next to every implemented skill.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parse } from "yaml";
import { z } from "zod";

const ROOT = path.resolve("skills");
const REQUIRED = ["id", "name", "version", "category", "description", "runtime", "executor", "cost", "status"] as const;

function findSkillDirs(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (!statSync(full).isDirectory()) continue;
    if (existsSync(path.join(full, "SKILL.md"))) out.push(full);
    else out.push(...findSkillDirs(full));
  }
  return out.sort();
}

function parseSkillMd(file: string) {
  const raw = readFileSync(file, "utf8");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const meta = parse(m[1]!) as Record<string, unknown>;
  for (const k of REQUIRED) if (meta[k] === undefined) throw new Error(`${file}: frontmatter is missing "${k}"`);
  for (const k of ["tags", "consumes", "produces", "dependencies", "failures"]) meta[k] = (meta[k] as string[] | undefined) ?? [];
  meta.version = String(meta.version);
  return { meta, instructions: m[2]!.trim() };
}

async function main() {
  const dirs = findSkillDirs(ROOT);
  const ids = new Set<string>();
  const imports: string[] = [];
  const entries: string[] = [];

  for (const [i, dir] of dirs.entries()) {
    const rel = path.relative(ROOT, dir);
    const { meta, instructions } = parseSkillMd(path.join(dir, "SKILL.md"));
    if (ids.has(meta.id as string)) throw new Error(`Duplicate skill id ${meta.id}`);
    ids.add(meta.id as string);
    const hasImpl = existsSync(path.join(dir, "skill.ts"));
    if (meta.status === "ready" && !hasImpl) throw new Error(`${rel}: status is ready but skill.ts is missing`);
    if (meta.status === "planned" && hasImpl) throw new Error(`${rel}: planned skills must not ship skill.ts`);

    if (hasImpl) {
      imports.push(`import s${i} from "./${rel}/skill";`);
      const mod = (await import(path.join(dir, "skill.ts"))).default as { id: string; input: z.ZodType; output: z.ZodType };
      if (mod.id !== meta.id) throw new Error(`${rel}: skill.ts id "${mod.id}" ≠ SKILL.md id "${meta.id}"`);
      const schema = {
        id: meta.id,
        version: meta.version,
        input: z.toJSONSchema(mod.input, { io: "input", unrepresentable: "any" }),
        output: z.toJSONSchema(mod.output, { io: "output", unrepresentable: "any" }),
      };
      writeFileSync(path.join(dir, "schema.json"), JSON.stringify(schema, null, 2) + "\n");
    }
    entries.push(`  { meta: ${JSON.stringify(meta)}, instructions: ${JSON.stringify(instructions)}, definition: ${hasImpl ? `s${i}` : "null"} },`);
  }

  const file = `// Generated by scripts/build-skills.ts. Do not edit; run \`pnpm skills:build\`.\nimport type { RegisteredSkill, SkillMeta } from "@/server/skills/types";\n${imports.join("\n")}\n\nexport const SKILLS: RegisteredSkill[] = [\n${entries.join("\n")}\n].map((s) => ({ ...s, meta: s.meta as SkillMeta }));\n`;
  writeFileSync(path.join(ROOT, "registry.generated.ts"), file);
  console.log(`✓ ${dirs.length} skills (${imports.length} implemented) → skills/registry.generated.ts`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
